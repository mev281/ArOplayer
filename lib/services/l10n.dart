class L10n {
  static final ValueNotifier<String> language = ValueNotifier<String>('tr');

  static const Map<String, String> languageNames = <String, String>{
    'tr': 'Türkçe',
    'en': 'English',
    'de': 'Deutsch',
  };
}

String t(String turkish) {
  final lang = L10n.language.value;
  if (lang == 'tr') return turkish;
  final fromApp = kAppStrings[turkish];
  if (fromApp != null && fromApp[lang] != null) return fromApp[lang]!;
  final fromPlayer = kPlayerStrings[turkish];
  if (fromPlayer != null && fromPlayer[lang] != null) return fromPlayer[lang]!;
  return turkish;
}
